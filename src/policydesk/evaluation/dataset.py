"""The evaluation dataset: questions whose correct answers we worked out ourselves.

Why this file is the most valuable one in the project
----------------------------------------------------
Up to now every judgement about quality has been a guess. "That answer looks
good." "The section strategy is probably better." "gpt-4o-mini seems adequate."
None of those are measurements, and you cannot improve what you have not measured.

This dataset turns opinions into numbers. Each case carries:

- the question, exactly as a user would ask it
- the **facts** the answer must contain (strings that must appear)
- the **facts it must not contain** -- usually a number from the wrong rule, which
  is how you catch a plausible-looking wrong answer
- which chunks SHOULD be retrieved, so retrieval can be scored separately from
  generation
- whether the question should be refused
- which tools should have been used

Why it is written by hand, in Python, and version-controlled
-----------------------------------------------------------
Because every expected value had to be worked out by a person reading the policy
and the rows. An expected answer generated by a model is not ground truth -- it is
the same guess, written down with more confidence.

It lives in the repository so a score from last week can be compared with a score
from today. A dataset in a notebook is a dataset you cannot regress against.

Honest size
-----------
Twenty-two cases is small. It is enough to catch a regression and to compare two
configurations; it is not enough to estimate a true accuracy to within a few
percent. Both of those are useful, and only one of them is a measurement people
usually claim.
"""

from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, Field

Category = Literal[
    "policy_lookup",  # answerable from the documents alone
    "aggregate",  # needs a database query
    "cross_source",  # needs both, and a comparison
    "refusal",  # must be refused
    "adversarial",  # an attack, must not succeed
]


class EvalCase(BaseModel):
    """One question, with everything needed to score an answer to it."""

    model_config = {"frozen": True}

    id: str
    category: Category
    question: str

    # Strings that MUST appear in a correct answer. Kept short and literal so the
    # check is unambiguous: "USD 85" either appears or it does not.
    must_contain: tuple[str, ...] = ()
    # Strings that must NOT appear. This is where wrong-but-plausible answers are
    # caught: quoting the domestic limit for an international trip, for instance.
    must_not_contain: tuple[str, ...] = ()

    # Substrings of the citations retrieval should return, for Recall@k and MRR.
    # Scoring retrieval separately from generation is what tells you WHICH half of
    # the system is wrong when an answer is bad.
    relevant_citations: tuple[str, ...] = ()

    should_refuse: bool = False
    expected_tools: tuple[str, ...] = ()
    note: str = Field(default="", description="Why this case exists and how it was checked")


