def cases_by_category(category: Category | None = None) -> tuple[EvalCase, ...]:
    if category is None:
        return CASES
    return tuple(case for case in CASES if case.category == category)


def case_by_id(case_id: str) -> EvalCase:
    for case in CASES:
        if case.id == case_id:
            return case
    raise KeyError(f"no evaluation case with id {case_id!r}")


def dataset_summary() -> dict[str, int]:
    counts: dict[str, int] = {}
    for case in CASES:
        counts[case.category] = counts.get(case.category, 0) + 1
    counts["total"] = len(CASES)
    return counts
