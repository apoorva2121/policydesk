"""Making a desktop icon that opens the tutor.

What this actually does
-----------------------
Three artefacts, all inside the project so they are reproducible:

1. `assets/policydesk.ico` — an icon, drawn here with Pillow rather than downloaded.
   A generated icon has no licence question attached to it and cannot rot.
2. `scripts/Learn PolicyDesk.cmd` — a launcher that finds the project's own virtual
   environment and runs the tutor in a window that **stays open**, having first
   started the study interface and the app itself and opened the study tool.
3. A Windows shortcut (`.lnk`) on the Desktop, pointing at the launcher, with the
   icon attached.

Why a `.cmd` launcher rather than pointing the shortcut straight at python
-------------------------------------------------------------------------
Because a shortcut to `python.exe -m policydesk.cli learn` closes the instant the
program ends, so any error message disappears with it. The launcher also sets the
working directory and checks the environment exists first, which turns "the icon
does nothing" into a sentence explaining why.

Why the shortcut is created by script rather than by hand
---------------------------------------------------------
So it can be recreated, and so this is documented in code rather than in somebody's
memory. It is also the only part that touches anything outside the project, which
is why it asks before writing to your Desktop.
"""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[3]
ASSETS = PROJECT_ROOT / "assets"
SCRIPTS = PROJECT_ROOT / "scripts"
ICON_PATH = ASSETS / "policydesk.ico"
LAUNCHER_PATH = SCRIPTS / "Learn PolicyDesk.cmd"
SHORTCUT_NAME = "Learn PolicyDesk.lnk"

# Sizes Windows actually asks for, from the taskbar up to large icons.
ICON_SIZES = (16, 24, 32, 48, 64, 128, 256)


def make_icon(path: Path = ICON_PATH) -> Path:
    """Draw the icon and write a multi-resolution .ico.

    One image at 256px and let Pillow downscale: a single source means the small
    sizes cannot drift from the large one. The design is deliberately simple
    because a 16px icon has about 200 usable pixels — detail at that size turns
    into mud.
    """
    from PIL import Image, ImageDraw

    size = 256
    image = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    draw = ImageDraw.Draw(image)

    ink = (31, 59, 87, 255)  # the same navy as the generated policy PDFs
    accent = (214, 158, 46, 255)
    paper = (248, 250, 252, 255)

    # A rounded document, because that is what this thing is about.
    draw.rounded_rectangle([34, 20, 206, 236], radius=18, fill=paper, outline=ink, width=9)

    # Lines of text, shortening like a real paragraph.
    for index, width in enumerate((120, 132, 104, 128, 96)):
        top = 62 + index * 26
        draw.rounded_rectangle([62, top, 62 + width, top + 11], radius=5, fill=ink)

    # A magnifying glass: retrieval, and the thing you are learning to inspect.
    draw.ellipse([120, 128, 212, 220], outline=accent, width=14)
    draw.line([200, 208, 232, 240], fill=accent, width=16)

    path.parent.mkdir(parents=True, exist_ok=True)
    image.save(path, format="ICO", sizes=[(n, n) for n in ICON_SIZES])
    return path


LAUNCHER_TEMPLATE = """@echo off
REM Opens the PolicyDesk tutor. Generated by `policydesk install-shortcut`.
REM
REM `cmd /k`-style behaviour is deliberate: the window stays open after the tutor
REM exits so you can read any message, instead of a shortcut that appears to do
REM nothing.

title Learn PolicyDesk
cd /d "{project}"

if not exist "{python}" (
    echo.
    echo  The project's Python environment is missing:
    echo    {python}
    echo.
    echo  Create it with:
    echo    uv venv --python 3.12 .venv
    echo    uv pip install -e .
    echo.
    pause
    exit /b 1
)

REM `--with-apps` is what makes one click enough: it starts the study interface and
REM the app itself, opens the STUDY TOOL in one browser tab (the app is linked from
REM its sidebar), and runs the tutor here. Anything already running on those ports is
REM reused and left alone.
"{python}" -m policydesk.cli learn --with-apps

echo.
echo  ------------------------------------------------------------------
echo   The tutor has closed. Your progress is saved.
echo   Run it again from this icon, or: policydesk learn --with-apps
echo   Just the tutor, no browser tabs:  policydesk learn
echo  ------------------------------------------------------------------
echo.
pause
"""


def make_launcher(path: Path = LAUNCHER_PATH) -> Path:
    """Write the .cmd launcher, pointing at this project's own interpreter."""
    python = PROJECT_ROOT / ".venv" / "Scripts" / "python.exe"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        LAUNCHER_TEMPLATE.format(project=PROJECT_ROOT, python=python),
        encoding="utf-8",
    )
    return path


def desktop_directory() -> Path | None:
    """Find the Desktop, honouring OneDrive redirection.

    Checked rather than assumed: on a machine with OneDrive the real Desktop is
    under the OneDrive folder, and writing to `%USERPROFILE%\\Desktop` there
    creates a shortcut nobody ever sees.
    """
    candidates = []
    # Upper case because Python normalises environment variable names on Windows,
    # where the variable is actually written `OneDrive`. Either spelling resolves;
    # upper case is the portable one.
    onedrive = os.environ.get("ONEDRIVE") or os.environ.get("ONEDRIVECONSUMER")
    if onedrive:
        candidates.append(Path(onedrive) / "Desktop")
    home = Path.home()
    candidates.append(home / "Desktop")
    candidates.append(home / "OneDrive" / "Desktop")

    for candidate in candidates:
        if candidate.is_dir():
            return candidate
    return None


SHORTCUT_SCRIPT = r"""
$ErrorActionPreference = 'Stop'
$shell = New-Object -ComObject WScript.Shell
$link = $shell.CreateShortcut('{shortcut}')
$link.TargetPath = '{target}'
$link.WorkingDirectory = '{workdir}'
$link.IconLocation = '{icon}'
$link.Description = 'Learn the PolicyDesk agentic RAG project, step by step'
$link.Save()
Write-Output 'created'
"""


def create_shortcut(destination: Path, launcher: Path, icon: Path) -> tuple[bool, str]:
    """Create the .lnk via PowerShell. Returns (succeeded, message).

    A failure here is reported, never raised: the icon is a convenience, and if it
    cannot be made you should still be told that the launcher itself works.
    """
    if sys.platform != "win32":
        return False, (
            "shortcut creation is Windows-only. On macOS or Linux, run the tutor with "
            "`policydesk learn`, or add a shell alias."
        )

    script = SHORTCUT_SCRIPT.format(
        shortcut=str(destination / SHORTCUT_NAME),
        target=str(launcher),
        workdir=str(PROJECT_ROOT),
        icon=str(icon),
    )
    try:
        completed = subprocess.run(
            ["powershell", "-NoProfile", "-NonInteractive", "-Command", script],
            capture_output=True,
            text=True,
            timeout=60,
            check=False,
        )
    except Exception as exc:  # noqa: BLE001
        return False, f"could not run PowerShell: {type(exc).__name__}: {exc}"

    if completed.returncode != 0 or "created" not in (completed.stdout or ""):
        detail = (completed.stderr or completed.stdout or "").strip().splitlines()
        return False, f"PowerShell refused: {detail[0] if detail else 'no detail'}"

    return True, str(destination / SHORTCUT_NAME)


def install(destination: Path | None = None) -> dict[str, object]:
    """Build the icon and launcher, and create the shortcut. Reports what happened."""
    icon = make_icon()
    launcher = make_launcher()

    target = destination or desktop_directory()
    if target is None:
        return {
            "icon": str(icon),
            "launcher": str(launcher),
            "shortcut": None,
            "message": (
                f"could not find your Desktop folder. The launcher works -- double-click {launcher}"
            ),
        }

    created, message = create_shortcut(target, launcher, icon)
    return {
        "icon": str(icon),
        "launcher": str(launcher),
        "shortcut": message if created else None,
        "message": message,
    }
